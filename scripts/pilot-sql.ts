// Writes the one-off migration that loads the pilot batches (content/batches) into the database,
// with the same ids the game uses (src/data/batchIds.ts). Run: npx tsx scripts/pilot-sql.ts
// Later batches go through the import (phase 5) instead.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { assignIds } from '../src/data/batchIds.ts'
import { batchSchema } from '../src/data/batchSchema.ts'

const batchDir = join(import.meta.dirname, '..', 'content', 'batches')
const out = join(
  import.meta.dirname,
  '..',
  'supabase',
  'migrations',
  '20261006000004_pilot_questions.sql',
)

const files = readdirSync(batchDir)
  .filter((name) => name.endsWith('.json'))
  .map((name) => ({
    name,
    items: batchSchema.parse(JSON.parse(readFileSync(join(batchDir, name), 'utf8'))),
  }))

const text = (value: string | null | undefined) =>
  value == null ? 'null' : `'${value.replaceAll("'", "''")}'`
const array = (values: readonly string[]) =>
  values.length === 0 ? `'{}'` : `array[${values.map(text).join(', ')}]::text[]`

const questions = assignIds(files)
const rows = questions.map((q) =>
  [
    text(q.id),
    text(q.topic),
    text(q.format),
    q.difficulty,
    text(q.status ?? (q.origin === 'own' ? 'approved' : 'review')),
    text(q.origin),
    text(q.source),
    array(q.tags),
    q.timeSensitive,
    q.checkedAt ? `${text(q.checkedAt)}::date` : 'null',
    text(q.editorNote),
  ].join(', '),
)
const texts = questions.map((q) =>
  [text(q.id), text(q.question), text(q.answer), array(q.accept), text(q.note)].join(', '),
)

writeFileSync(
  out,
  `-- Pilot questions from content/batches (generated by scripts/pilot-sql.ts; do not edit by hand).
-- ${questions.length} questions, status as in the files (review until approved in the editor).

insert into public.questions
  (id, topic_id, format, difficulty, status, origin, source, tags, time_sensitive, checked_at, editor_note)
values
${rows.map((row) => `  (${row})`).join(',\n')};

insert into public.question_texts (question_id, question, answer, accept, note)
values
${texts.map((row) => `  (${row})`).join(',\n')};
`,
)
console.log(`${questions.length} questions → ${out}`)
